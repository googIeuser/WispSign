"""Runtime dependency closure of WispSign: version lock and license notices.

    python packaging/third_party.py lock              -> requirements-lock.txt
    python packaging/third_party.py notices <out.txt> -> THIRD_PARTY_NOTICES.txt

Both read the installed environment only (importlib.metadata + packaging,
which pymobiledevice3 already requires), so no extra dependency is needed.

Run it by path, never as ``-m packaging...``: the repo's ``packaging/`` folder
must not become a Python package (no ``__init__.py``), or it would shadow the
``packaging`` library imported below.
"""

import sys
from importlib import metadata
from pathlib import Path

from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

ROOT = Path(__file__).resolve().parent.parent
LOCK_FILE = ROOT / "requirements-lock.txt"
ZSIGN_LICENSE = ROOT / "third_party" / "zsign" / "LICENSE"
PROJECT = "wispsign"

BUNDLED_TOOLS = ("pyinstaller",)
_LICENSE_PREFIXES = ("license", "licence", "copying", "notice")
_RULE = "=" * 78
INTRO = (
    "WispSign bundles the third-party software listed below. WispSign itself\n"
    "is licensed under the GNU GPL v3 or later (see LICENSE).\n"
)


def _wanted(req: Requirement, extras: frozenset[str]) -> bool:
    if req.marker is None:
        return True
    return any(req.marker.evaluate({"extra": extra}) for extra in extras | {""})


def runtime_closure(root: str = PROJECT) -> list[metadata.Distribution]:
    pass
    found: dict[str, metadata.Distribution] = {}
    queue: list[tuple[str, frozenset[str]]] = [(root, frozenset())]
    seen: set[tuple[str, frozenset[str]]] = set()
    while queue:
        name, extras = queue.pop()
        key = (canonicalize_name(name), extras)
        if key in seen:
            continue
        seen.add(key)
        dist = metadata.distribution(name)
        if key[0] != canonicalize_name(root):
            found[key[0]] = dist
        for line in dist.requires or ():
            req = Requirement(line)
            if _wanted(req, extras):
                queue.append((req.name, frozenset(req.extras)))
    return [found[name] for name in sorted(found)]


def lock_text() -> str:
    lines = [
        "# Exact runtime dependency versions for release builds.",
        "# Generated by: python packaging/third_party.py lock (from the verified .venv).",
        "# Use as constraints: pip install -c requirements-lock.txt -e .[dev]",
    ]
    lines += [
        f"{canonicalize_name(d.metadata['Name'])}=={d.version}"
        for d in runtime_closure()
    ]
    return "\n".join(lines) + "\n"


def _license_files(dist: metadata.Distribution) -> list[str]:
    texts = []
    for file in dist.files or ():
        parts = Path(str(file)).parts
        leaf = parts[-1].lower()
        in_metadata = any(p.endswith((".dist-info", ".egg-info")) for p in parts)
        if in_metadata and leaf.startswith(_LICENSE_PREFIXES):
            try:
                texts.append(Path(dist.locate_file(file)).read_text(encoding="utf-8"))
            except (OSError, UnicodeDecodeError):
                continue
    return texts


def _license_field(dist: metadata.Distribution) -> str:
    meta = dist.metadata
    field = meta.get("License-Expression") or meta.get("License") or ""
    if field and len(field) < 200:
        return field
    classifiers = [
        c.removeprefix("License :: ")
        for c in meta.get_all("Classifier") or ()
        if c.startswith("License ::")
    ]
    return "; ".join(classifiers) or ("see the license text below" if field else "")


def _section(title: str, license_name: str, texts: list[str]) -> str:
    body = "\n\n".join(t.strip() for t in texts) or "(no license file shipped)"
    return (
        f"{_RULE}\n{title}\nLicense: {license_name or 'unknown'}\n{_RULE}\n\n{body}\n"
    )


def notices_text() -> str:
    sections = [INTRO]
    dists = runtime_closure()
    names = {canonicalize_name(d.metadata["Name"]) for d in dists}
    for tool in BUNDLED_TOOLS:
        if canonicalize_name(tool) not in names:
            dists.append(metadata.distribution(tool))
    for dist in dists:
        title = f"{dist.metadata['Name']} {dist.version}"
        sections.append(_section(title, _license_field(dist), _license_files(dist)))
    python_license = Path(sys.base_prefix) / "LICENSE.txt"
    if python_license.is_file():
        version = ".".join(map(str, sys.version_info[:3]))
        text = python_license.read_text(encoding="utf-8", errors="replace")
        sections.append(_section(f"Python {version}", "PSF-2.0", [text]))
    sections.append(
        _section("zsign", "MIT", [ZSIGN_LICENSE.read_text(encoding="utf-8")])
    )
    return "\n".join(sections)


def main(argv: list[str]) -> int:
    if argv[:1] == ["lock"] and len(argv) == 1:
        LOCK_FILE.write_text(lock_text(), encoding="utf-8", newline="\n")
        return 0
    if argv[:1] == ["notices"] and len(argv) == 2:
        out = Path(argv[1])
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(notices_text(), encoding="utf-8", newline="\n")
        return 0
    print(__doc__, file=sys.stderr)
    return 2


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
